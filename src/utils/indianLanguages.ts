/**
 * Get translated Day name
 */
export function getDayName(dayName: string, lang: LanguageCode | string = 'en'): string {
  const safeLang = (lang as LanguageCode) || 'en';
  for (const day of Object.keys(DAY_TRANSLATIONS)) {
    if (dayName.includes(day)) {
      const translated = DAY_TRANSLATIONS[day][safeLang] || day;
      return dayName.replace(day, translated);
    }
  }
  return dayName;
}

