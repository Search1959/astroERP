/**
 * Get translated text helper
 */
export function getTranslation(key: string, lang: LanguageCode | string = 'en'): string {
  const safeLang = (lang as LanguageCode) || 'en';
  if (UI_TRANSLATIONS[key] && UI_TRANSLATIONS[key][safeLang]) {
    return UI_TRANSLATIONS[key][safeLang];
  }
  if (UI_TRANSLATIONS[key] && UI_TRANSLATIONS[key]['en']) {
    return UI_TRANSLATIONS[key]['en'];
  }
  return key;
}

