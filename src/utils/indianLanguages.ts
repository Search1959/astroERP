/**
 * Get translated Status name (e.g. Excellent -> अति उत्तम)
 */
export function getStatusName(status: string, lang: LanguageCode | string = 'en'): string {
  const safeLang = (lang as LanguageCode) || 'en';
  switch (status.toLowerCase()) {
    case 'excellent':
      return UI_TRANSLATIONS.statusExcellent?.[safeLang] || status;
    case 'favorable':
      return UI_TRANSLATIONS.statusFavorable?.[safeLang] || status;
    case 'steady':
      return UI_TRANSLATIONS.statusSteady?.[safeLang] || status;
    case 'caution':
      return UI_TRANSLATIONS.statusCaution?.[safeLang] || status;
    default:
      return status;
  }
}

